import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
}

android {
    namespace = "co.nsgsolutions.spinola"
    compileSdk = 37

    defaultConfig {
        applicationId = "co.nsgsolutions.spinola"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // Release signing: android/spinola-upload.jks and android/keystore.properties (both gitignored;
    // see docs/PLAY-STORE.md). storeFile is relative to android/. Without them a release build is
    // signed with the debug key, which installs locally but Play Console refuses.
    val keystoreProps = rootProject.file("keystore.properties")
    if (keystoreProps.exists()) {
        val props = Properties().apply { keystoreProps.inputStream().use { load(it) } }
        signingConfigs {
            create("upload") {
                storeFile = rootProject.file(props.getProperty("storeFile"))
                storePassword = props.getProperty("storePassword")
                keyAlias = props.getProperty("keyAlias")
                keyPassword = props.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            // Without the upload key the release build is signed with the debug key, so it can be
            // installed and smoke-tested locally after R8. Play refuses debug-signed uploads outright,
            // so this can never reach the store by accident.
            signingConfig = signingConfigs.getByName(if (keystoreProps.exists()) "upload" else "debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    sourceSets {
        // The question content is shared with the iOS app: content/assets/decks.json is written by
        // OlaBallTests/CrossPlatformExportTests.swift and shipped here as an asset.
        getByName("main") {
            kotlin.directories.add("src/main/kotlin")
            assets.directories.add("../../content/assets")
        }
        getByName("test") {
            kotlin.directories.add("src/test/kotlin")
        }
        getByName("androidTest") {
            kotlin.directories.add("src/androidTest/kotlin")
        }
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }

    packaging {
        resources.excludes += setOf("META-INF/AL2.0", "META-INF/LGPL2.1", "META-INF/LICENSE*")
    }
}

